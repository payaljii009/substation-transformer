/* ============================================================================
   2. VIRTUAL INSULATION RESISTANCE CALCULATION ENGINE
   ============================================================================ */

const InsulationModel = {
  /**
   * Computes simulated apparent insulation resistance (in MΩ) at a given
   * elapsed test time t (0 to 60 seconds).
   *
   * Educational model principles:
   * 1. Base resistance depends on simulated health condition and HV/LV class.
   * 2. Temperature follows an approximate inverse halving rule every ~12°C rise.
   * 3. Humidity reduces resistance (amplified on contaminated/porcelain surfaces).
   * 4. Apparent R(t) rises over 0-60s as capacitive + absorption currents decay.
   */
  calculateSimulatedIR({
    bushingId = "HV-A",
    material = "porcelain",
    condition = "healthy",
    tempC = 25,
    humidityPct = 45,
    voltageV = 2500,
    elapsedSec = 60,
    includeNoise = false
  }) {
    const profile = INSULATION_PROFILES[condition] || INSULATION_PROFILES.healthy;
    const isHV = bushingId.startsWith("HV");

    // 1. Base steady-state resistance in MΩ
    let rSteady = isHV ? profile.hvBaseSteadyMOhm : profile.lvBaseSteadyMOhm;

    // 2. Material surface factor: composite silicone rubber resists moisture filming slightly better
    const materialFactor =
      material === "composite"
        ? 1.0 + Math.max(0, (humidityPct - 50) * 0.003)
        : 1.0;

    // 3. Temperature correction concept: halves roughly per 12°C rise above 25°C
    const tempFactor = Math.pow(0.5, (tempC - 25) / 12);

    // 4. Moisture / Relative Humidity degradation factor (normalized around 45% RH)
    const deltaRH = Math.max(0, humidityPct - 35) / 60; // 0 at <=35%, 1 at 95%
    const humidityFactor = Math.max(
      0.18,
      1.0 - deltaRH * 0.55 * profile.humiditySensitivity
    );

    // 5. Mild voltage stress sensitivity on degraded/faulty insulation
    const voltageRatio = (Number(voltageV) - 1000) / 4000;
    const voltageSensitivity =
      condition === "healthy" ? 0.02 : condition === "aged" ? 0.08 : 0.16;
    const voltageFactor = Math.max(0.75, 1.0 - voltageRatio * voltageSensitivity);

    rSteady = rSteady * materialFactor * tempFactor * humidityFactor * voltageFactor;

    // 6. Time-dependent charging + dielectric absorption rise over 0..60 seconds
    const t = Math.max(0, Math.min(60, elapsedSec));
    const capComponent = 0.18 * Math.exp(-t / 2.2);
    const absFraction = 1 - profile.initialFraction;
    const riseProgress = 1 - Math.exp(-t / profile.absorptionTau);
    const timeMultiplier =
      (profile.initialFraction + absFraction * riseProgress) / (1 + capComponent);

    let rApparent = rSteady * timeMultiplier;

    // Optional small realistic readout jitter for live virtual display (off for deterministic tests)
    if (includeNoise) {
      const jitter = 1 + (Math.random() - 0.5) * 0.015;
      rApparent *= jitter;
    }

    return Math.max(0.2, Number(rApparent.toFixed(2)));
  },

  /**
   * Formats a Megaohm value cleanly into MΩ or GΩ for dashboard display.
   */
  formatResistance(megaOhms) {
    if (megaOhms === null || megaOhms === undefined || Number.isNaN(megaOhms)) {
      return "-- MΩ";
    }
    if (megaOhms >= 1000) {
      return `${(megaOhms / 1000).toFixed(2)} GΩ`;
    }
    if (megaOhms >= 100) {
      return `${megaOhms.toFixed(1)} MΩ`;
    }
    return `${megaOhms.toFixed(2)} MΩ`;
  },

  /**
   * Generates a full 0..60 second curve array at 1-second intervals.
   */
  generateCurve(params) {
    const points = [];
    for (let sec = 0; sec <= 60; sec += 1) {
      points.push(
        this.calculateSimulatedIR({
          ...params,
          elapsedSec: sec,
          includeNoise: false
        })
      );
    }
    return points;
  }
};

