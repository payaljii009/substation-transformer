  onParametersChanged() {
    const params = this.getParams();
    document.getElementById("readout-voltage").textContent = `${params.voltageV} V DC`;
    this.refreshBaselineAndChart();
    ChartManager.updateComparisonChart(params);
  },

  refreshBaselineAndChart() {
    const params = this.getParams();
    const showBaseline = document.getElementById("chk-baseline").checked;
    const baselineCurve = InsulationModel.generateCurve({
      ...params,
      condition: "healthy"
    });
    ChartManager.updateRTChart(this.activeSeries, baselineCurve, showBaseline);
  },

  startSimulation() {
    this.stopTimer();
    const params = this.getParams();

    this.isRunning = true;
    this.elapsedSec = 0;
    this.activeSeries = [];
    this.r15 = null;
    this.r30 = null;
    this.r60 = null;

    this.setStatusLED("running", "SIMULATING...");
    document.getElementById("btn-log-result").disabled = true;
    this.updateSampleStrip();

    // Record t = 0 initial point immediately
    this.stepSimulation(params);

    const intervalMs = Math.max(80, Math.round(1000 / params.speed));
    this.timerHandle = setInterval(() => {
      if (this.elapsedSec >= 60) {
        this.completeSimulation(params);
        return;
      }
      this.elapsedSec += 1;
      this.stepSimulation(this.getParams());
    }, intervalMs);
  },

  stepSimulation(params) {
    const reading = InsulationModel.calculateSimulatedIR({
      ...params,
      elapsedSec: this.elapsedSec,
      includeNoise: true
    });

    this.activeSeries.push(reading);

    if (this.elapsedSec === 15) this.r15 = reading;
    if (this.elapsedSec === 30) this.r30 = reading;
    if (this.elapsedSec === 60) this.r60 = reading;

    // Update LCD Readout
    document.getElementById("readout-resistance").textContent =
      InsulationModel.formatResistance(reading);
    document.getElementById("readout-timer").textContent =
      `${String(this.elapsedSec).padStart(2, "0")}s / 60s`;
    document.getElementById("sim-progress-bar").style.width =
      `${(this.elapsedSec / 60) * 100}%`;

    this.updateSampleStrip();
    this.refreshBaselineAndChart();

    if (this.elapsedSec >= 60) {
      this.completeSimulation(params);
    }
  },

  completeSimulation(params) {
    this.stopTimer();
    this.isRunning = false;
    this.setStatusLED("complete", "COMPLETE (VIRTUAL)");
    document.getElementById("btn-log-result").disabled = false;
    this.renderInterpretation(params);
  },

  /**
   * Immediately generates a full 0..60s simulated curve and sample readings
   * for quick classroom demonstrations without waiting.
   */
