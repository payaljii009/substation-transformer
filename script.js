    this.stopTimer();
    const params = this.getParams();
    this.isRunning = false;
    this.elapsedSec = 60;
    this.activeSeries = InsulationModel.generateCurve(params);
    this.r15 = this.activeSeries[15];
    this.r30 = this.activeSeries[30];
    this.r60 = this.activeSeries[60];

