const VerificationSuite = {
  runAll() {
    const results = [];
    const check = (name, category, expected, fn) => {
      try {
        const { pass, observed } = fn();
        results.push({ name, category, expected, observed, pass });
      } catch (err) {
        results.push({
          name,
          category,
          expected,
          observed: `Error: ${err.message}`,
          pass: false
        });
      }
    };

    // 1. Unit Formatting & Finite Value Check
    check(
      "MΩ & GΩ Unit Formatting",
      "Virtual Calculations",
      "< 1000 MΩ in MΩ; >= 1000 MΩ in GΩ",
      () => {
        const a = InsulationModel.formatResistance(420.5);
        const b = InsulationModel.formatResistance(4250);
        const pass = a.includes("MΩ") && b === "4.25 GΩ";
        return { pass, observed: `420.5 -> "${a}", 4250 -> "${b}"` };
      }
    );

    // 2. Condition Ordering
    check(
      "Condition Resistance Hierarchy",
      "Virtual Calculations",
      "Healthy > Aged > Contaminated > Faulty",
      () => {
        const base = { bushingId: "HV-A", material: "porcelain", tempC: 25, humidityPct: 45, voltageV: 2500, elapsedSec: 60 };
        const h = InsulationModel.calculateSimulatedIR({ ...base, condition: "healthy" });
        const a = InsulationModel.calculateSimulatedIR({ ...base, condition: "aged" });
        const c = InsulationModel.calculateSimulatedIR({ ...base, condition: "contaminated" });
        const f = InsulationModel.calculateSimulatedIR({ ...base, condition: "faulty" });
        const pass = h > a && a > c && c > f;
        return {
          pass,
          observed: `${InsulationModel.formatResistance(h)} > ${InsulationModel.formatResistance(a)} > ${InsulationModel.formatResistance(c)} > ${InsulationModel.formatResistance(f)}`
        };
      }
    );

    // 3. Temperature Inverse Law
    check(
      "Temperature Inverse Relationship",
      "Environmental Physics",
      "IR(20 °C) > IR(50 °C)",
      () => {
        const base = { bushingId: "HV-A", material: "porcelain", condition: "healthy", humidityPct: 45, voltageV: 2500, elapsedSec: 60 };
        const r20 = InsulationModel.calculateSimulatedIR({ ...base, tempC: 20 });
        const r50 = InsulationModel.calculateSimulatedIR({ ...base, tempC: 50 });
        return {
          pass: r20 > r50,
          observed: `20°C: ${InsulationModel.formatResistance(r20)} vs 50°C: ${InsulationModel.formatResistance(r50)}`
        };
      }
    );

    // 4. Moisture Degradation Law
    check(
      "Humidity / Moisture Degradation",
      "Environmental Physics",
      "IR(30% RH) > IR(90% RH)",
      () => {
        const base = { bushingId: "HV-A", material: "porcelain", condition: "contaminated", tempC: 25, voltageV: 2500, elapsedSec: 60 };
        const rDry = InsulationModel.calculateSimulatedIR({ ...base, humidityPct: 30 });
        const rWet = InsulationModel.calculateSimulatedIR({ ...base, humidityPct: 90 });
        return {
          pass: rDry > rWet,
          observed: `30% RH: ${InsulationModel.formatResistance(rDry)} vs 90% RH: ${InsulationModel.formatResistance(rWet)}`
        };
      }
    );

    // 5. Dielectric Absorption Time Curve
    check(
      "Dielectric Absorption Trend (0s-60s)",
      "Megger Theory",
      "Healthy R(60s) > R(15s) > R(1s)",
      () => {
        const base = { bushingId: "HV-A", material: "porcelain", condition: "healthy", tempC: 25, humidityPct: 45, voltageV: 2500 };
        const r1 = InsulationModel.calculateSimulatedIR({ ...base, elapsedSec: 1 });
        const r15 = InsulationModel.calculateSimulatedIR({ ...base, elapsedSec: 15 });
        const r60 = InsulationModel.calculateSimulatedIR({ ...base, elapsedSec: 60 });
        return {
          pass: r60 > r15 && r15 > r1,
          observed: `1s: ${InsulationModel.formatResistance(r1)}, 15s: ${InsulationModel.formatResistance(r15)}, 60s: ${InsulationModel.formatResistance(r60)}`
        };
      }
    );

    // 6. Instant Sample & Reset Workflow
    check(
      "Interactive Sample & Reset Cycle",
      "UI State & Reset",
      "Sample populates 60s data; Reset clears active readings & defaults sliders",
      () => {
        SimulationController.generateInstantSample();
        const populated = SimulationController.r60 !== null && SimulationController.activeSeries.length === 61;
        SimulationController.resetSimulation();
        const resetClean =
          SimulationController.r60 === null &&
          SimulationController.activeSeries.length === 0 &&
          document.getElementById("readout-resistance").textContent === "-- MΩ" &&
          document.getElementById("slider-temp").value === "25";
        return {
          pass: populated && resetClean,
          observed: `Populated=${populated}, ResetRestored=${resetClean}`
        };
      }
    );

    // 7. Chart.js Binding
    check(
      "Chart.js Graph Instances & Updates",
      "Data Visualization",
      "R-t and Comparison charts initialized with 61 time points",
      () => {
        if (typeof Chart === "undefined") {
          return { pass: false, observed: "Chart.js CDN unavailable (offline)" };
        }
        const rtOk = ChartManager.rtChart && ChartManager.rtChart.data.labels.length === 61;
        const compOk = ChartManager.comparisonChart && ChartManager.comparisonChart.data.datasets.length === 4;
        return {
          pass: Boolean(rtOk && compOk),
          observed: `R-t Chart=${Boolean(rtOk)}, Comparison Chart=${Boolean(compOk)}`
        };
      }
    );

    // 8. Three.js 3D Model Integrity
    check(
      "Three.js 3D Bushings & Material Toggle",
      "3D Visualization",
      "3 HV + 4 LV bushings present & material switchable",
      () => {
        if (typeof THREE === "undefined" || !ThreeSceneManager.isReady) {
          return { pass: false, observed: "Three.js / WebGL unavailable in current browser context" };
        }
        const keys = Object.keys(ThreeSceneManager.bushingGroups);
        const hasAll = ["HV-A", "HV-B", "HV-C", "LV-a", "LV-b", "LV-c", "LV-n"].every((k) =>
          keys.includes(k)
        );
        ThreeSceneManager.setMaterial("composite");
        const switchedComp = ThreeSceneManager.currentMaterial === "composite";
        ThreeSceneManager.setMaterial("porcelain");
        const switchedPorc = ThreeSceneManager.currentMaterial === "porcelain";
        return {
          pass: hasAll && switchedComp && switchedPorc,
          observed: `Bushings=${keys.length}/7, MaterialToggle=${switchedComp && switchedPorc}`
        };
      }
    );

    this.renderResults(results);
    return results;
  },

  renderResults(results) {
    const total = results.length;
    const passed = results.filter((r) => r.pass).length;
    const failed = total - passed;

    document.getElementById("v-total").textContent = total;
    document.getElementById("v-passed").textContent = passed;
    document.getElementById("v-failed").textContent = failed;

    const tbody = document.getElementById("verification-tbody");
    tbody.innerHTML = "";
    results.forEach((r, idx) => {
      const tr = document.createElement("tr");
      tr.innerHTML = `
        <td>${idx + 1}</td>
        <td><strong>${r.name}</strong></td>
        <td>${r.category}</td>
        <td>${r.expected}</td>
        <td>${r.observed}</td>
        <td><span class="pill ${r.pass ? "status-good" : "status-poor"}">${r.pass ? "PASS" : "FAIL"}</span></td>
      `;
      tbody.appendChild(tr);
    });
  }
};

/* ============================================================================
   8. NAVIGATION & APPLICATION BOOTSTRAP
   ============================================================================ */

function setupNavigation() {
  const navButtons = document.querySelectorAll(".nav-btn");
  const panels = document.querySelectorAll(".tab-panel");

  navButtons.forEach((btn) => {
    btn.addEventListener("click", () => {
      const target = btn.dataset.tab;

      navButtons.forEach((b) => b.classList.toggle("active", b === btn));
      panels.forEach((p) => p.classList.toggle("active", p.id === `tab-${target}`));

      if (target === "simulation") {
        ThreeSceneManager.handleResize();
      } else if (target === "results") {
        ChartManager.updateComparisonChart(SimulationController.getParams());
      } else if (target === "verification") {
        VerificationSuite.runAll();
      }
    });
  });
}

document.addEventListener("DOMContentLoaded", () => {
  setupNavigation();
  ThreeSceneManager.init();
  ChartManager.init();
  SimulationController.init();
  ResultsManager.init();

  document.getElementById("btn-run-verification").addEventListener("click", () => {
    VerificationSuite.runAll();
  });

  // Run initial verification silently so summary table is populated immediately
  VerificationSuite.runAll();
});
